/*
 * GLOSSARY: one name per concept (i18n-copy-8).
 *
 * Every string table (this file, workspace.ts) and the README use the words below, and
 * i18n/__tests__/glossary.test.ts fails when a banned variant comes back. When a new string needs
 * one of these concepts, use the word of the table; when it needs a new concept, add a row.
 *
 * concept                      zh              en                           ja
 * ---------------------------- --------------- ---------------------------- ---------------------------
 * the floating ball            悬浮球          floating bubble (the bubble) フローティングボタン
 * panel folds into the ball    收起            collapse                     収納
 * panel goes to the tray       隐藏到系统托盘  hide to the system tray      システムトレイに隠す
 * long content (code, notes)   折叠 / 展开     show less / show more        折りたたむ / 展開
 * an entry of a category       条目            item                         項目
 * the seven categories         文件夹 网站 软件 密码 命令 备忘 任务
 *                              Folders Sites Apps Passwords Commands Notes Tasks
 *                              フォルダ サイト アプリ パスワード コマンド メモ タスク
 *                              (the page heading of a category is its tab name: sec_x = tab_x)
 * a folder                     文件夹          folder                       フォルダ
 * the remark field of an item  备注            Note                         備考
 *
 * Three folding words, never mixed: the panel collapses INTO THE BALL (收起 / collapse / 収納), it is
 * HIDDEN to the tray (隐藏 / hide / 隠す), and long content is FOLDED or unfolded (折叠 / show less /
 * 折りたたむ). 展开 / 展開 is the one opening word, for the panel coming out of the ball and for
 * content alike.
 *
 * English is written in sentence case everywhere ("Add item", "Export data", "Folders & files"):
 * a capital only for the first word and for proper names (Marubako, Windows, Edge, Chrome).
 * Names of keys are as on the keyboard (Esc, Ctrl, Alt).
 *
 * Keys keep their names when a value changes; other packages add keys next to these without
 * touching them.
 */

